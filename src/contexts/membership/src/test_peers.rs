//! Valid Ed25519 public keys used as `PeerId` fixtures across this crate's
//! tests.
//!
//! These are the published RFC 8032 §7.1 test-vector public keys, so they are
//! known-good encodings without this crate depending on any crypto library or
//! random number generator. They are fixtures only: nothing here performs real
//! Ed25519 maths.
//!
//! The session-collapse rule (canvas §2.5/3) is ordered by `PeerId`'s
//! lexicographic `Ord` over key bytes, so [`all`] deliberately spans a wide
//! range of leading bytes — `0x27`, `0x3d`, `0xd7`, `0xec`, `0xfc` — and is
//! *not* sorted, which keeps ordering assertions from passing by accident.

use shared_types::PeerId;

