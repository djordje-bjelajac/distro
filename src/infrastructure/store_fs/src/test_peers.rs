//! Valid Ed25519 public keys used as `PeerId` fixtures across this crate's
//! tests.
//!
//! These are the published RFC 8032 §7.1 test-vector public keys, so they are
//! known-good encodings that do not depend on this crate's random source — a
//! fixture that changed every run would make a stored file impossible to assert
//! against byte for byte.
//!
//! Deliberately a duplicate of the equivalent fixture file in the context
//! crates: contexts never import each other (canvas §4), a shared test-fixture
//! crate would be exactly such a coupling, and an infrastructure crate reaching
//! into a context's private test module could not compile anyway.

use shared_types::PeerId;

