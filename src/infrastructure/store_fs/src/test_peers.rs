fn peer(bytes: [u8; 32]) -> PeerId {
    PeerId::from_public_key_bytes(bytes).expect("RFC 8032 test vector must be a valid public key")
}

pub(crate) fn alice() -> PeerId {
    peer(ALICE_PUBLIC_KEY)
}

pub(crate) fn bob() -> PeerId {
    peer(BOB_PUBLIC_KEY)
}

pub(crate) fn carol() -> PeerId {
    peer(CAROL_PUBLIC_KEY)
}
